"""Static snapshot access: the model's ONLY system knowledge.

snapshot.json is generated by scripts/regen_schema_snapshot.py, reviewed by a
human, and committed. It contains schema metadata, rules, dimensions, and the
intent vocabulary — never employee-level data. Drift checks compare the live
database shape against the snapshot so staleness fails loudly (more
`unsupported` replies, never wrong data).
"""
from __future__ import annotations

import json
from pathlib import Path

from sqlalchemy import text
from sqlalchemy.orm import Session

SNAPSHOT_PATH = Path(__file__).resolve().parent / "snapshot.json"

ALLOWED_TOP_KEYS = {"version", "generated_at", "tables", "rules", "dimensions", "intents", "definitions"}


def load() -> dict:
    with open(SNAPSHOT_PATH, encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict) or set(data.keys()) - ALLOWED_TOP_KEYS:
        raise ValueError("snapshot.json has an unexpected shape")
    return data


def live_columns(session: Session, table: str) -> list[str]:
    """Ordered column names for one live table (shape only, no values)."""
    rows = session.execute(
        text(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = 'public' AND table_name = :t ORDER BY ordinal_position"
        ),
        {"t": table},
    ).fetchall()
    return [r[0] for r in rows]


def summarize(snap: dict, max_rules_chars: int = 4000) -> str:
    """Compact prompt text: tables, rules (truncated), intents, definitions."""
    lines = ["TABLES (name: columns):"]
    for t, cols in snap.get("tables", {}).items():
        lines.append(f"- {t}: {', '.join(cols)}")
    rules_text = json.dumps(snap.get("rules", {}))[:max_rules_chars]
    lines.append(f"RULES: {rules_text}")
    lines.append(f"INTENTS: {', '.join(snap.get('intents', []))}")
    defs = snap.get("definitions", {})
    if defs:
        lines.append("DEFINITIONS: " + " | ".join(f"{k} = {v}" for k, v in defs.items()))
    return "\n".join(lines)


def fingerprint_live(session: Session) -> str:
    """Hash of the live shape (table/column names + rule keys) for drift checks."""
    cols = session.execute(
        text(
            "SELECT table_name || '.' || column_name FROM information_schema.columns "
            "WHERE table_schema = 'public' ORDER BY 1"
        )
    ).fetchall()
    shape = "|".join(r[0] for r in cols)
    return hashlib.sha256(shape.encode()).hexdigest()[:16]


def fingerprint_snapshot(snap: dict) -> str:
    shape = "|".join(
        f"{t}.{c}" for t in sorted(snap.get("tables", {})) for c in snap["tables"][t]
    )
    return hashlib.sha256(shape.encode()).hexdigest()[:16]
